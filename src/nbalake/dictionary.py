from __future__ import annotations

import duckdb

from nbalake import datasets
from nbalake.models import ALL
from nbalake.models.model import CURATED


def render(con: duckdb.DuckDBPyConnection) -> str:
    rows = con.execute(
        """
        SELECT schema_name, table_name, column_name, data_type
        FROM duckdb_columns()
        WHERE database_name = 'lake' AND schema_name <> 'meta'
        ORDER BY schema_name, table_name, column_index
        """
    ).fetchall()
    tables: dict[tuple[str, str], list[tuple[str, str]]] = {}
    for schema, table, col, typ in rows:
        tables.setdefault((schema, table), []).append((col, typ))
    counts = {
        (s, t): n
        for s, t, n in con.execute(
            "SELECT schema_name, table_name, estimated_size FROM duckdb_tables() "
            "WHERE database_name = 'lake'"
        ).fetchall()
    }
    descriptions = {(d.schema, d.table): d.description for d in datasets.ALL}
    sorts = {(d.schema, d.table): (d.partition, d.sort) for d in datasets.ALL}
    for m in ALL:
        sorts[(CURATED, m.name)] = (m.partition, m.sort)
        descriptions[(CURATED, m.name)] = m.description
    out = [
        "# Data dictionary",
        "",
        "Generated by `nbalake dictionary` from the registry and the catalog.",
        "",
    ]
    for (schema, table), cols in tables.items():
        out.append(f"## {schema}.{table}")
        out.append("")
        if desc := descriptions.get((schema, table)):
            out.append(desc)
            out.append("")
        partition, sort = sorts.get((schema, table), (None, ()))
        facts = [f"rows: {counts.get((schema, table), 0):,}"]
        if partition:
            facts.append(f"partitioned by `{partition}`")
        if sort:
            facts.append("sorted by " + ", ".join(f"`{c}`" for c in sort))
        out.append(". ".join(facts) + ".")
        out.append("")
        out.append("| column | type |")
        out.append("|---|---|")
        out.extend(f"| `{c}` | {t} |" for c, t in cols)
        out.append("")
    return "\n".join(out)
